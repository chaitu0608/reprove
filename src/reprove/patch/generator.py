_GENERATORS = {
    "secrets/committed-env": _gen_committed_env,
    "secrets/supabase-service-role": _gen_secret_literal,
    "secrets/openai-key": _gen_secret_literal,
    "secrets/anthropic-key": _gen_secret_literal,
    "secrets/stripe-secret": _gen_secret_literal,
    "secrets/aws-access-key": _gen_secret_literal,
    "secrets/github-token": _gen_secret_literal,
    "secrets/slack-token": _gen_secret_literal,
    "secrets/google-api-key": _gen_secret_literal,
    "secrets/high-entropy": _gen_secret_literal,
    "rls/table-without-rls": _gen_rls,
    "rls/permissive-policy": _gen_permissive_policy,
    "authz/node-admin-route-no-auth": _gen_node_admin_guard,
    "idor/in-memory-find-by-id": _gen_idor_inmemory,
    "idor/supabase-fetch-by-id": _gen_idor_supabase,
    "injection/sql-string-concat": _gen_sql_concat,
    "config/cors-wildcard": _gen_cors,
    "deps/nonexistent-package": _gen_remove_dep,
}


def propose_patch(ctx: ScanContext, finding: Finding) -> Optional[Patch]:
    gen = _GENERATORS.get(finding.rule)
    if not gen:
        return _manual_patch(finding, "no automated fix template for this rule yet")
    try:
        return gen(ctx, finding)
    except Exception as e:  # never crash the audit on one generator
        return _manual_patch(finding, f"patch generator error: {e!r}")


def propose_all(ctx: ScanContext, findings: list[Finding]) -> list[Patch]:
    return [p for f in findings if (p := propose_patch(ctx, f)) is not None]


# ---- applying patches ---------------------------------------------------------------------


def apply_patch(repo: Path, patch: Patch) -> list[str]:
    """Apply one patch in place. Returns human-readable change notes."""
    changes: list[str] = []
    for edit in patch.edits:
        path = repo / edit["path"]
        if not path.exists():
            changes.append(f"SKIP {edit['path']}: file missing")
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if edit["old"] not in text:
            changes.append(f"SKIP {edit['path']}: target text not found")
            continue
        path.write_text(text.replace(edit["old"], edit["new"], 1), encoding="utf-8")
        changes.append(f"patched {edit['path']}")
    for relpath, content in patch.new_files.items():
        p = repo / relpath
        p.parent.mkdir(parents=True, exist_ok=True)
        if p.exists():
            with p.open("a", encoding="utf-8") as fh:
                fh.write("\n" + content if not content.startswith("\n") else content)
            changes.append(f"appended {relpath}")
        else:
            p.write_text(content, encoding="utf-8")
            changes.append(f"created {relpath}")
    for relpath in patch.deletions:
        p = repo / relpath
        if p.exists():
            p.unlink()
            changes.append(f"deleted {relpath}")
    return changes
