"""Patch generator: deterministic, template-based minimal fixes.

Design rule: a fix is only generated when the transformation is mechanical
and safe (literal replacement, guard insertion against an auth helper that
provably exists in the file, SQL concat -> parameter placeholder, RLS
migration generation). Everything else returns a `manual` patch containing
precise guidance — we would rather admit "this one is on you" than ship a
patch that deletes the wrong line. The verifier is the backstop either way.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Optional

from ..context import ScanContext
from ..models import Finding, Patch
from ..util import unified_diff

PLACEHOLDER = "REMOVED_BY_REPROVE__ROTATE_ME"


# ---- helpers -----------------------------------------------------------------------


def _read(repo: Path, relpath: str) -> Optional[str]:
    p = repo / relpath
    if not p.exists() or p.is_dir():
        return None
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def _location_file(finding: Finding) -> Optional[str]:
    loc = finding.location
    if loc.startswith(("GET ", "POST ", "http://", "https://")) or loc.startswith("/"):
        return None
    if re.match(r"^[^:]+:\d+$", loc):
        return loc.rsplit(":", 1)[0]
    return loc if "/" in loc else None


def _line_no(finding: Finding) -> Optional[int]:
    if re.match(r"^[^:]+:\d+$", finding.location):
        return int(finding.location.rsplit(":", 1)[1])
    return None


def _make_edit(repo: Path, relpath: str, old: str, new: str) -> Optional[dict]:
    current = _read(repo, relpath)
    if current is None or old not in current:
        return None
    return {"path": relpath, "old": old, "new": new, "kind": "modify"}


def _patch_with(repo: Path, finding: Finding, summary: str, edits: list[dict],
                new_files: dict[str, str] | None = None,
                deletions: list[str] | None = None, note: str = "") -> Patch:
    diff_parts = []
    for e in edits:
        current = _read(repo, e["path"]) or ""
        diff_parts.append(unified_diff(current, current.replace(e["old"], e["new"], 1), e["path"]))
    for path, content in (new_files or {}).items():
        diff_parts.append(f"--- /dev/null\n+++ b/{path}\n" +
                          "".join(f"+{ln}\n" for ln in content.splitlines()))
    for path in deletions or []:
        diff_parts.append(f"--- a/{path}\n+++ /dev/null (file deleted)")
    return Patch(
        finding_id=finding.id,
        summary=summary,
        edits=edits,
        new_files=new_files or {},
        deletions=deletions or [],
        diff="\n".join(p for p in diff_parts if p),
        note=note,
        automatic=True,
    )


def _manual_patch(finding: Finding, reason: str) -> Patch:
    return Patch(
        finding_id=finding.id,
        summary=f"Manual fix required: {finding.title}",
        note=f"{reason}\n\nRecommended fix:\n{finding.remediation}",
        automatic=False,
    )


# ---- per-rule generators --------------------------------------------------------------

def _gen_committed_env(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f) or ".env"
    text = _read(ctx.root, relpath)
    if text is None:
        return _manual_patch(f, "could not read the env file")
    example = re.sub(r"=(.*)", "=", text)
    example = "# Generated by reprove from " + relpath + " — fill values locally, never commit them.\n" + example
    gi = _read(ctx.root, ".gitignore")
    new_files = {".env.example": example}
    edits = []
    if gi is None or ".env" not in gi.split("\n"):
        new_files[".gitignore"] = (gi or "") + "\n# reprove: never commit env files\n.env\n.env.local\n.env.*.local\n"
    return _patch_with(ctx.root, f,
                       f"Remove committed {relpath}, add .env.example and .gitignore rules. ROTATE the leaked keys.",
                       edits, new_files=new_files, deletions=[relpath],
                       note="Deleting the file does NOT un-leak its values: rotate every credential that was in it, "
                            "and purge the file from git history before making the repo public.")


def _gen_secret_literal(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    line_no = _line_no(f)
    if not relpath or not line_no:
        return _manual_patch(f, "could not locate the exact line")
    if relpath.endswith((".env", ".env.local", ".env.production")):
        return _manual_patch(f, "this secret lives in a committed env file — use the `secrets/committed-env` fix "
                                "(delete file + .env.example + rotation)")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    lines = current.splitlines()
    if line_no - 1 >= len(lines):
        return _manual_patch(f, "line moved since the scan")
    line = lines[line_no - 1]

    literal = None
    m = re.search(r"""["'`]([^"'`]{16,300})["'`]""", line)
    if m:
        literal = m.group(1)
    if literal is None:
        return _manual_patch(f, "no replaceable string literal found on the line")
    if literal.strip() in ("", PLACEHOLDER):
        return _manual_patch(f, "value already removed")

    marker = "// reprove: exposed secret removed — rotate the credential"
    new_line = line.replace(literal, "", 1).rstrip()
    if not new_line.endswith(";"):
        new_line += ";"
    new_line += " " + marker
    edit = _make_edit(ctx.root, relpath, line, new_line)
    if not edit:
        return _manual_patch(f, "could not apply replacement")
    return _patch_with(ctx.root, f,
                       f"Remove the exposed secret from {relpath}:{line_no}",
                       [edit],
                       note="The value is removed from source, but it was already exposed: rotate it now. "
                            "If a client-side feature depended on it, proxy that call through your server.")


def _gen_rls(ctx: ScanContext, f: Finding) -> Patch:
    table = f.metadata.get("table", "")
    if not table:
        return _manual_patch(f, "table name missing from finding")
    short = table.split(".")[-1].replace('"', "")
    owner = f.metadata.get("has_owner_column")
    stmts = [f"-- reprove: lock down RLS for {table}",
             f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;"]
    if not owner:
        stmts += [f"-- {short} has no owner column. This migration assumes `user_id`; adjust if your model differs.",
                  f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id);"]
    for action, check in (("SELECT", "USING (auth.uid() = user_id)"),
                          ("INSERT", "WITH CHECK (auth.uid() = user_id)"),
                          ("UPDATE", "USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id)"),
                          ("DELETE", "USING (auth.uid() = user_id)")):
        stmts.append(f"CREATE POLICY \"{short}_{action.lower()}_own\" ON {table} FOR {action} {check};")
    content = "\n".join(stmts) + "\n"
    filename = f"supabase/migrations/9{int(hashlib.md5(table.encode()).hexdigest()[:4], 16) % 10000:04d}_reprove_rls_{short}.sql"
    return _patch_with(ctx.root, f,
                       f"Add RLS lockdown migration for `{table}`",
                       [], new_files={filename: content},
                       note="Review the generated policy before applying: it assumes rows are owned via `user_id`. "
                            "Run it against a staging database first (supabase db push / migration runner).")


def _gen_permissive_policy(ctx: ScanContext, f: Finding) -> Patch:
    table = f.metadata.get("table", "")
    policy = f.metadata.get("policy", "")
    if not table or not policy:
        return _manual_patch(f, "table/policy metadata missing")
    short = table.split(".")[-1].replace('"', "")
    content = (
        f"-- reprove: replace permissive policy `{policy}` on {table}\n"
        f"DROP POLICY IF EXISTS \"{policy}\" ON {table};\n"
        f"CREATE POLICY \"{policy}_scoped\" ON {table}\n"
        f"  FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);\n"
    )
    filename = f"supabase/migrations/9{int(hashlib.md5((table + policy).encode()).hexdigest()[:4], 16) % 10000:04d}_reprove_policy_{short}.sql"
    return _patch_with(ctx.root, f, f"Scope permissive policy `{policy}` on `{table}`", [],
                       new_files={filename: content},
                       note="Verify the owner column assumption (user_id) against your schema before applying.")


NODE_ADMIN_BLOCK = re.compile(
    r"""req\.url\s*\.startsWith\s*\(\s*['"`](?P<path>/api/(?:admin|internal)[^'"`]*)['"`]\s*\)[^{]*\{"""
)
AUTH_HELPER = re.compile(r"(?:function\s+auth\s*\(|const\s+auth\s*=|let\s+auth\s*=|var\s+auth\s*=)")


def _gen_node_admin_guard(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    if not relpath:
        return _manual_patch(f, "could not locate the handler file")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    if not AUTH_HELPER.search(current):
        return _manual_patch(f, "no local `auth(req)` helper exists in this file to reuse — add auth middleware manually")
    m = NODE_ADMIN_BLOCK.search(current)
    if not m:
        return _manual_patch(f, "could not locate the admin route block (it may have changed)")
    if re.search(r"function\s+deny\s*\(", current):
        deny_name = "deny"
    else:
        deny_fn = re.search(r"function\s+(\w+)\s*\(\s*res\s*,\s*(?:code|status)", current)
        deny_name = deny_fn.group(1) if deny_fn else "deny"
    old = m.group(0)
    guard = (old + "\n    const __rpUser = auth(req);\n"
             f"    if (!__rpUser) {{ return {deny_name}(res, 401); }}")
    edit = _make_edit(ctx.root, relpath, old, guard)
    if not edit:
        return _manual_patch(f, "replacement target not found")
    return _patch_with(ctx.root, f, f"Require auth on admin block in {relpath}", [edit],
                       note="This closes anonymous access. Consider also adding a role check — "
                            "authentication is not authorization.")


IDOR_FIND = re.compile(
    r"(?P<coll>\w+)\.find\(\s*(?:function\s*)?\(?\s*(?P<el>\w+)\s*\)?\s*=>?\s*(?:\{\s*return\s+)?(?P=el)\.id\s*===\s*(?P<id>[\w.]+)"
)
LOCAL_USER_VAR = re.compile(r"const\s+(?P<var>\w+)\s*=\s*auth\s*\(\s*req")


def _gen_idor_inmemory(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    if not relpath:
        return _manual_patch(f, "could not locate the lookup")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    um = LOCAL_USER_VAR.search(current)
    m = IDOR_FIND.search(current)
    if not m:
        return _manual_patch(f, "lookup pattern changed since the scan — apply manually")
    if not um:
        return _manual_patch(f, "no `const user = auth(req)` in scope — add the ownership check manually")
    user_var = um.group("var")
    old = m.group(0)
    new = old + f" && {m.group('el')}.userId === {user_var}.id"
    edit = _make_edit(ctx.root, relpath, old, new)
    if not edit:
        return _manual_patch(f, "replacement target not found")
    return _patch_with(ctx.root, f, f"Scope id lookup to the authenticated user in {relpath}", [edit],
                       note=f"The lookup now requires row.userId === {user_var}.id. Adapt the ownership "
                            f"field (`userId`) if your schema names it differently.")


SUPABASE_CHAIN = re.compile(r"(?P<pre>\.eq\(\s*['\"`]id['\"`]\s*,\s*[^)]+\))")
SUPABASE_USER = re.compile(r"const\s*\{\s*data\s*:\s*\{\s*user\s*\}\s*\}\s*=\s*await\s+\w+\.auth\.getUser\(\)")


def _gen_idor_supabase(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    if not relpath:
        return _manual_patch(f, "could not locate the query")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    if not SUPABASE_USER.search(current):
        return _manual_patch(f, "no `const { data: { user } } = await supabase.auth.getUser()` in the file — add scoping manually")
    changed = SUPABASE_CHAIN.sub(lambda m: m.group("pre") + ".eq('user_id', user.id)", current, count=1)
    if changed == current:
        return _manual_patch(f, "query chain pattern changed since the scan")
    # build edit from the first differing region
    for old_line, new_line in zip(current.splitlines(), changed.splitlines()):
        if old_line != new_line:
            edit = _make_edit(ctx.root, relpath, old_line, new_line)
            if edit:
                return _patch_with(ctx.root, f, f"Scope supabase query to the caller in {relpath}", [edit],
                                   note="Query now filters by user_id. Verify the table's owner column name "
                                        "(`user_id` assumed). RLS remains your backstop.")
    return _manual_patch(f, "could not isolate the change")


# Matches:  const sql = "…LIKE '%" + q + "%'";
SQL_CONCAT_LIKE = re.compile(
    r'''(?P<stmt>const\s+(?P<name>\w+)\s*=\s*)"(?P<a>[^"]*LIKE\s+'%)"\s*\+\s*(?P<var>\w+)\s*\+\s*"(?P<b>%')"'''
)
SQL_QUERY_CALL = re.compile(r"(?P<fn>\w+\.(?:query|execute|raw))\s*\(\s*(?P<name>\w+)\s*\)")


def _gen_sql_concat(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    if not relpath:
        return _manual_patch(f, "could not locate the SQL statement")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    m = SQL_CONCAT_LIKE.search(current)
    if not m:
        return _manual_patch(f, "SQL concat shape not recognized — parameterize manually "
                                "(pass values as bound parameters, never interpolate)")
    name, var = m.group("name"), m.group("var")
    # "… LIKE '%"  ->  "… LIKE ?"     and the user value moves to a params array
    head = m.group("a")[:-2]  # drop the trailing `'%`
    new_stmt = (f'{m.group("stmt")}"{head}?"; '
                f'const {name}Params = ["%" + {var} + "%"]')
    edits: list[dict] = []
    old_stmt = m.group(0)
    if old_stmt in current:
        edits.append({"path": relpath, "old": old_stmt, "new": new_stmt, "kind": "modify"})
    call = SQL_QUERY_CALL.search(current)
    if call and call.group("name") == name:
        edits.append({"path": relpath, "old": call.group(0),
                      "new": f"{call.group('fn')}({name}, {name}Params)", "kind": "modify"})
    if not edits:
        return _manual_patch(f, "replacement target vanished")
    return _patch_with(ctx.root, f, f"Parameterize SQL query `{name}` in {relpath}", edits,
                       note=f"The query now uses a `?` placeholder with values passed separately as "
                            f"`{name}Params`. Check your database driver's parameter binding syntax "
                            "(`?`, `$1`, or `:name`) — adjust if it differs.")


CORS_WILDCARD_HEADER = re.compile(
    r"""(?P<key>['"]Access-Control-Allow-Origin['"])\s*(?P<sep>[:,])\s*['"]\*['"]"""
)
CORS_WILDCARD_EXPRESS = re.compile(r"""origin\s*:\s*['"]\*['"]""")


def _gen_cors(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f)
    if not relpath:
        return _manual_patch(f, "could not locate the CORS setting")
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read the file")
    if m := CORS_WILDCARD_HEADER.search(current):
        old = m.group(0)
        new = (f"{m.group('key')}{m.group('sep')} "
               "process.env.ALLOWED_ORIGIN || 'http://localhost:3000'")
    elif m := CORS_WILDCARD_EXPRESS.search(current):
        old = m.group(0)
        new = "origin: (process.env.ALLOWED_ORIGIN || 'http://localhost:3000')"
    else:
        return _manual_patch(f, "CORS pattern changed since the scan")
    edit = _make_edit(ctx.root, relpath, old, new)
    if not edit:
        return _manual_patch(f, "replacement failed")
    return _patch_with(ctx.root, f, f"Restrict CORS origin in {relpath}", [edit],
                       note="Set ALLOWED_ORIGIN in your production environment to your real frontend URL.")


def _gen_remove_dep(ctx: ScanContext, f: Finding) -> Patch:
    relpath = _location_file(f) or "package.json"
    current = _read(ctx.root, relpath)
    if current is None:
        return _manual_patch(f, "could not read package.json")
    name = None
    for ev in f.evidence:
        mm = re.search(r"registry\.npmjs\.org/([^\s]+)", ev.detail)
        if mm:
            name = mm.group(1)
            break
        mm = re.search(r"`([@\w/.-]+)@", ev.detail)
        if mm:
            name = mm.group(1)
            break
    if not name:
        return _manual_patch(f, "could not determine the package name from evidence")
    target = None
    for ln in current.splitlines():
        if re.match(rf'\s*"{re.escape(name)}"\s*:', ln):
            target = ln
            break
    if target is None:
        return _manual_patch(f, f"could not find the `{name}` entry in package.json")
    new_content = "\n".join(ln for ln in current.splitlines() if ln != target) + "\n"
    return Patch(
        finding_id=f.id,
        summary=f"Remove nonexistent dependency `{name}`",
        edits=[{"path": relpath, "old": target + "\n", "new": "", "kind": "modify"}],
        diff=unified_diff(current, new_content, relpath),
        note=f"`{name}` is not on the npm registry. Fix the import to the intended real package, then re-install.",
        automatic=True,
    )


